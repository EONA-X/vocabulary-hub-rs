//! Per-slug `.htaccess`: Accept-header content negotiation with mod_rewrite.
//!
//! mod_rewrite rather than mod_negotiation type maps (`.var`) because it is the
//! one module every Apache-style static host enables. The cost is that
//! `q`-values are not weighed: the first rule whose media type appears in
//! `Accept` wins, in the order JSON-LD, Turtle, HTML. Anything else — `*/*`
//! included — gets HTML, the representation a person following a link can use;
//! RDF clients always name an RDF media type.
//!
//! The rules match any `{version}` whose `{version}.ttl` is on disk rather than
//! the versions of this build: upstream keeps only the latest version, so a
//! later build no longer knows an earlier one, but that earlier version's IRIs
//! were published and must keep resolving (deploys never delete them).

use std::fmt::Write;

pub fn render(slug: &str, versions: &[&str]) -> String {
  let mut s = String::from(
    "# Generated by vocabulary-hub-build. Do not edit: rebuild instead.
AddType text/turtle .ttl
AddType application/ld+json .jsonld
AddCharset utf-8 .ttl .jsonld .html
Options -MultiViews -Indexes
<IfModule mod_headers.c>
  Header merge Vary Accept
</IfModule>
RewriteEngine On
",
  );
  let _ = writeln!(s, "RewriteBase /{slug}/");
  // Behind eona-x.eu's apex router this directory is really voc/{slug}/; only
  // requests routed there (an internal redirect) may reach it.
  let _ = writeln!(
    s,
    "RewriteCond %{{ENV:REDIRECT_STATUS}} ^$\nRewriteCond %{{REQUEST_URI}} !^/{slug}(/|$)\nRewriteRule ^ - [R=404,L]"
  );
  for (accept, ext) in [(r"application/(ld\+)?json", "jsonld"), ("text/turtle", "ttl"), ("", "html")] {
    let _ = writeln!(s, "\nRewriteCond %{{REQUEST_FILENAME}} !-f\nRewriteCond %{{REQUEST_FILENAME}}.ttl -f");
    if !accept.is_empty() {
      let _ = writeln!(s, "RewriteCond %{{HTTP_ACCEPT}} {accept} [NC]");
    }
    let _ = writeln!(s, "RewriteRule ^([^/]+)$ $1.{ext} [L]");
  }
  if let Some(latest) = versions.iter().max_by(|a, b| version_key(a).cmp(&version_key(b))) {
    let _ = writeln!(s, "\n# {slug}/ -> latest version of this build\nRewriteRule ^$ {latest} [R=302,L]");
  }
  s
}

/// `v1.10.0` sorts after `v1.9.0`; a non-numeric segment sorts as 0.
fn version_key(version: &str) -> Vec<u64> {
  version.trim_start_matches('v').split('.').map(|n| n.parse().unwrap_or(0)).collect()
}
