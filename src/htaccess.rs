//! Per-slug `.htaccess`: Accept-header content negotiation with mod_rewrite.
//!
//! mod_rewrite rather than mod_negotiation type maps (`.var`) because it is the
//! one module every Apache-style static host enables. The cost is that
//! `q`-values are not weighed: the first rule whose media type appears in
//! `Accept` wins, in the order JSON-LD, Turtle, HTML. Anything else — `*/*`
//! included — gets HTML, the representation a person following a link can use;
//! RDF clients always name an RDF media type.
//!
//! The rules match any `{version}` whose `{version}.ttl` is on disk rather than
//! the versions of this build: upstream keeps only the latest version, so a
//! later build no longer knows an earlier one, but that earlier version's IRIs
//! were published and must keep resolving (deploys never delete them).
//!
//! The configured stylesheets no longer live under a slug directory (they
//! are shared once per asset type, at `../assets/` from here — see
//! [`crate::site::write_site`]), so this file's own compression rule only
//! needs to cover what it actually serves; [`render_assets`] is the shared
//! `assets/` directory's own small `.htaccess`, giving `text/css` its
//! compression there instead.

use std::fmt::Write;

/// `slug_path` is `{asset-class}/{slug}`, the directory this file lives in on
/// `host`, the production host that publishes it.
pub fn render(host: &str, slug_path: &str, versions: &[&str]) -> String {
  let mut s = String::from(
    "# Generated by vocabulary-hub-build. Do not edit: rebuild instead.
AddType text/turtle .ttl
AddType application/ld+json .jsonld
AddCharset utf-8 .ttl .jsonld .html
Options -MultiViews -Indexes
# A page's every representation is text, and the largest HTML pages run to
# hundreds of KB uncompressed -- no host observed so far compresses these by
# a platform default the way it does for some other types.
<IfModule mod_deflate.c>
  AddOutputFilterByType DEFLATE text/html text/turtle application/ld+json
</IfModule>
<IfModule mod_headers.c>
  Header merge Vary Accept
</IfModule>
# eona-x.eu's own WordPress .htaccess denies .html/.htm by extension (its
# webshell-upload guard); the asset-type router rewrites every HTML
# representation here internally to a real .html file, so without this
# override the host that most needs the HTML variant is the one that 403s it.
# Legacy Allow (not Require: this host's AllowOverride grants Limit, the
# WordPress .htaccess's own equivalent override for its own files uses the
# same legacy form, not AuthConfig).
<FilesMatch \"\\.html?$\">
  Allow from all
</FilesMatch>
RewriteEngine On
",
  );
  let _ = writeln!(s, "RewriteBase /{slug_path}/");
  // Read by dev-voc's root overlay (hosting/dev/.htaccess), which names the
  // production twin of every response as canonical; it serves both hosts'
  // trees side by side. Set on every pass, before the rules that end one.
  let _ = writeln!(s, "RewriteRule ^ - [E=CANONICAL_HOST:{host}]");
  // Behind eona-x.eu's apex router this directory is really voc/{slug_path}/; only
  // requests routed there (an internal redirect) may reach it.
  let _ = writeln!(
    s,
    "RewriteCond %{{ENV:REDIRECT_STATUS}} ^$\nRewriteCond %{{REQUEST_URI}} !^/{}(/|$)\nRewriteRule ^ - [R=404,L]",
    escape_regex(slug_path)
  );
  for (accept, ext) in [(r"application/(ld\+)?json", "jsonld"), ("text/turtle", "ttl"), ("", "html")] {
    let _ = writeln!(s, "\nRewriteCond %{{REQUEST_FILENAME}} !-f\nRewriteCond %{{REQUEST_FILENAME}}.ttl -f");
    if !accept.is_empty() {
      let _ = writeln!(s, "RewriteCond %{{HTTP_ACCEPT}} {accept} [NC]");
    }
    let _ = writeln!(s, "RewriteRule ^([^/]+)$ $1.{ext} [L]");
  }
  if let Some(latest) = versions.iter().max_by(|a, b| version_key(a).cmp(&version_key(b))) {
    // Absolute, on the request's own host: with a relative target Apache builds
    // the URL itself, and behind OVH's TLS front it adds ":443". The sites
    // are HTTPS-only (dev redirects plain HTTP), hence the fixed scheme.
    let _ = writeln!(
      s,
      "\n# {slug_path}/ -> latest version of this build\nRewriteRule ^$ https://%{{HTTP_HOST}}/{}/{latest} [R=302,L]",
      escape_substitution(slug_path)
    );
  }
  s
}

/// `.htaccess` for the `assets/` directory [`crate::site::write_site`] shares
/// across every slug of one asset type on one host (`{host}/{kind}/assets/`):
/// the configured stylesheets live there, once, rather than under each slug
/// (its own largest files: ~80KB uncompressed for a full design-system
/// stylesheet). Their own compression, since a slug's `.htaccess` only
/// cascades down its own tree, never sideways to this sibling directory.
pub fn render_assets() -> String {
  "# Generated by vocabulary-hub-build. Do not edit: rebuild instead.
AddType text/css .css
AddCharset utf-8 .css
<IfModule mod_deflate.c>
  AddOutputFilterByType DEFLATE text/css
</IfModule>
"
  .to_string()
}

/// Backslash-escapes every non-alphanumeric ASCII character so `slug` matches literally in a RewriteCond regex.
fn escape_regex(slug: &str) -> String {
  slug.chars().fold(String::new(), |mut out, c| {
    if c.is_ascii() && !c.is_ascii_alphanumeric() && c != '/' && c != '-' && c != '_' {
      out.push('\\');
    }
    out.push(c);
    out
  })
}

/// Escapes `$` and `%`, which a RewriteRule substitution would expand as backreferences.
fn escape_substitution(slug: &str) -> String {
  slug.replace('$', "\\$").replace('%', "\\%")
}

/// `v1.10.0` sorts after `v1.9.0`; a non-numeric segment sorts as 0.
fn version_key(version: &str) -> Vec<u64> {
  version.trim_start_matches('v').split('.').map(|n| n.parse().unwrap_or(0)).collect()
}

#[cfg(test)]
mod tests {
  use super::render;

  #[test]
  fn regex_metacharacters_in_the_slug_are_escaped_in_the_request_uri_guard() {
    let out = render("vocabulary-hub.example", "ontology/a+b(c)*", &["v1.0.0"]);
    assert!(out.contains(r"RewriteCond %{REQUEST_URI} !^/ontology/a\+b\(c\)\*(/|$)"), "{out}");
  }

  #[test]
  fn substitution_backreference_characters_in_the_slug_are_escaped() {
    let out = render("vocabulary-hub.example", "ontology/a$1%2", &["v1.0.0"]);
    assert!(out.contains(r"https://%{HTTP_HOST}/ontology/a\$1\%2/v1.0.0 [R=302,L]"), "{out}");
  }
}
